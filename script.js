// Render Gallery Function
function renderGallery(filter = 'All') {
    const grid = document.getElementById('galleryGrid');
    let itemsToRender = [];

    // Select appropriate gallery based on filter
    switch(filter) {
        case 'All':
            itemsToRender = allViewGallery;
            break;
        case 'Wedding':
            itemsToRender = weddingGallery;
            break;
        case 'PreWedding':
            itemsToRender = preWeddingGallery;
            break;
        case 'Fashion':
            itemsToRender = fashionGallery;
            break;
        case 'Travel':
            itemsToRender = travelGallery;
            break;
        case 'Commercial':
            itemsToRender = commercialGallery;
            break;
        case 'BabyShower':
            itemsToRender = babyShowerGallery;
            break;
        default:
            itemsToRender = allViewGallery;
    }

    // Generate HTML for gallery items with category-specific styling
    grid.innerHTML = itemsToRender.map(item => `
        <div class="gallery-item ${item.category.toLowerCase()}-item" data-category="${item.category}">
            <img src="${item.src}" alt="${item.title}" loading="lazy">
            <div class="gallery-item-overlay">
                <div class="gallery-item-content">
                    <h3 class="gallery-item-title">${item.title}</h3>
                    <p class="gallery-item-category">${item.category.replace(/([A-Z])/g, ' $1').trim()}</p>
                </div>
            </div>
        </div>
    `).join('');
}

// Filter Button Functionality
function initializeFilters() {
    const filterButtons = document.querySelectorAll('.filter-btn');
    
    filterButtons.forEach(btn => {
        btn.addEventListener('click', function() {
            // Remove active class from all buttons
            filterButtons.forEach(b => b.classList.remove('active'));
            
            // Add active class to clicked button
            this.classList.add('active');
            
            // Render gallery with selected filter
            renderGallery(this.dataset.filter);
            
            // Re-initialize scroll animations for new items
            setTimeout(initializeScrollAnimations, 100);
        });
    });
}

