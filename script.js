// Open Video Modal
function openVideoModal(videoType, isBehindScenes = false) {
    const modal = document.getElementById('videoModal');
    const video = document.getElementById('modalVideo');
    const videoSource = document.getElementById('videoSource');
    const videoTitle = document.getElementById('videoTitle');
    const videoDescription = document.getElementById('videoDescription');
    
    const videoInfo = videoData[videoType];
    
    if (!videoInfo) {
        console.error('Video type not found:', videoType);
        return;
    }
    
    // Set video source
    const videoFile = isBehindScenes ? videoInfo.behindScenes : videoInfo.videoFile;
    videoSource.src = videoFile;
    
    // Set video info
    videoTitle.textContent = isBehindScenes ? `${videoInfo.title} - Behind the Scenes` : videoInfo.title;
    videoDescription.textContent = videoInfo.description;
    
    // Load and play video
    video.load();
    
    // Show modal
    modal.classList.add('active');
    document.body.style.overflow = 'hidden';
    
    // Auto-play video
    setTimeout(() => {
        video.play().catch(err => {
            console.log('Auto-play prevented:', err);
        });
    }, 300);
    
    // Handle video end
    video.onended = function() {
        // Video ended, keep modal open with controls visible
        console.log('Video playback completed');
    };
}

// Close Video Modal
function closeVideoModal() {
    const modal = document.getElementById('videoModal');
    const video = document.getElementById('modalVideo');
    
    // Pause and reset video
    video.pause();
    video.currentTime = 0;
    
    // Hide modal
    modal.classList.remove('active');
    document.body.style.overflow = '';
}

// Initialize Video Buttons
function initializeVideoButtons() {
    // Create modal on initialization
    createVideoModal();
    
    // Close button handler
    const closeBtn = document.getElementById('closeVideoBtn');
    if (closeBtn) {
        closeBtn.addEventListener('click', closeVideoModal);
    }
    
    // Click outside modal to close
    const modal = document.getElementById('videoModal');
    if (modal) {
        modal.addEventListener('click', function(e) {
            if (e.target === modal) {
                closeVideoModal();
            }
        });
    }
    
    // Escape key to close
    document.addEventListener('keydown', function(e) {
        if (e.key === 'Escape') {
            const modal = document.getElementById('videoModal');
            if (modal && modal.classList.contains('active')) {
                closeVideoModal();
            }
        }
    });
    
    // Video project click handlers - FIXED for pre-wedding video
    const videoProjects = document.querySelectorAll('.video-project');
    videoProjects.forEach((project) => {
        const videoType = project.dataset.videoType;
        const videoFrame = project.querySelector('.video-frame');
        const watchBtn = project.querySelector('.btn-primary');
        const btsBtn = project.querySelector('.btn-outline');
        
        // Video frame click
        if (videoFrame && videoType) {
            videoFrame.addEventListener('click', function() {
                openVideoModal(videoType, false);
            });
        }
        
        // Watch Film button
        if (watchBtn && videoType) {
            watchBtn.addEventListener('click', function(e) {
                e.stopPropagation();
                openVideoModal(videoType, false);
            });
        }
        
        // Behind Scenes button
        if (btsBtn && videoType) {
            btsBtn.addEventListener('click', function(e) {
                e.stopPropagation();
                openVideoModal(videoType, true);
            });
        }
    });
}

