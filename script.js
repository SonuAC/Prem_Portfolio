// Open PDF Modal
function openPDFModal(projectId, projectTitle) {
    const modal = document.getElementById('pdfModal');
    const pdfViewer = document.getElementById('pdfViewer');
    const pdfProjectTitle = document.getElementById('pdfProjectTitle');
    const pdfNotFound = document.getElementById('pdfNotFound');
    
    // Set project title
    pdfProjectTitle.textContent = `${projectTitle} - Quotation`;
    
    // Check if PDF exists for this project
    if (projectPDFs[projectId]) {
        // Show PDF
        pdfViewer.src = projectPDFs[projectId];
        pdfViewer.style.display = 'block';
        pdfNotFound.style.display = 'none';
    } else {
        // Show not found message
        pdfViewer.style.display = 'none';
        pdfNotFound.style.display = 'flex';
    }
    
    // Show modal
    modal.classList.add('active');
    document.body.style.overflow = 'hidden';
}

// Close PDF Modal
function closePDFModal() {
    const modal = document.getElementById('pdfModal');
    const pdfViewer = document.getElementById('pdfViewer');
    
    // Reset viewer
    pdfViewer.src = '';
    
    // Hide modal
    modal.classList.remove('active');
    document.body.style.overflow = '';
}

// Download PDF
function downloadPDF() {
    const modal = document.getElementById('pdfModal');
    const pdfViewer = document.getElementById('pdfViewer');
    
    if (pdfViewer.src && pdfViewer.style.display !== 'none') {
        const link = document.createElement('a');
        link.href = pdfViewer.src;
        
        // Extract filename from the src
        const fileName = pdfViewer.src.split('/').pop();
        link.download = fileName;
        
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
    } else {
        alert('No PDF available to download.');
    }
}

